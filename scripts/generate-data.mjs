import { readFile, readdir, mkdir, rename, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { parseArgs } from "node:util";
import { load, JSON_SCHEMA } from "js-yaml";
import { dataSchemas, siteDataSchema } from "../lib/data-schema.ts";

const root = fileURLToPath(new URL("../", import.meta.url));
const input = path.join(root, "data");
const output = path.join(input, "index.ts");
const { values } = parseArgs({ options: { watch: { type: "boolean", default: false } } });

export async function generateData() {
  const files = (await readdir(input)).filter((file) => /\.ya?ml$/.test(file)).sort();
  const raw = {};
  for (const file of files) {
    const name = path.parse(file).name;
    if (!(name in dataSchemas)) throw new Error(`Unknown data file: ${file}`);
    if (Object.hasOwn(raw, name)) throw new Error(`Duplicate data file: ${file}`);
    // Preserve dates as strings instead of YAML timestamp objects.
    raw[name] = load(await readFile(path.join(input, file), "utf8"), {
      schema: JSON_SCHEMA,
      filename: file,
    });
  }
  const data = siteDataSchema.parse(raw);
  const content = `// Generated by scripts/generate-data.mjs. Edit data/*.yml instead.\nimport type { SiteData } from "../lib/data-schema";\nexport type { Section, Publication } from "../lib/data-schema";\n\nconst content: SiteData = ${JSON.stringify(data, null, 2)};\n\nexport const data = {\n${Object.keys(
    data,
  )
    .map((key) => `  ${key}: () => content.${key},`)
    .join("\n")}\n};\n`;
  if ((await readFile(output, "utf8").catch(() => "")) === content) return;
  await mkdir(input, { recursive: true });
  await writeFile(`${output}.tmp`, content);
  await rename(`${output}.tmp`, output);
  console.log(`Generated ${files.length} validated data collections.`);
}

// Queue changes arriving during generation so the final edit is never dropped.
let queue = Promise.resolve();
function schedule() {
  queue = queue.then(generateData).catch((error) => {
    console.error(error);
    if (!values.watch) process.exitCode = 1;
  });
  return queue;
}
if (values.watch) {
  const { watch } = await import("chokidar");
  const watcher = watch(input, {
    ignoreInitial: true,
    awaitWriteFinish: { stabilityThreshold: 150, pollInterval: 50 },
  });
  let timer;
  watcher.on("all", (_event, file) => {
    if (!/\.ya?ml$/.test(file)) return;
    clearTimeout(timer);
    timer = setTimeout(schedule, 100);
  });
  watcher.on("error", (error) => {
    console.error(error);
    process.exitCode = 1;
  });
  watcher.on("ready", schedule);
  for (const signal of ["SIGINT", "SIGTERM"])
    process.once(signal, async () => {
      clearTimeout(timer);
      await watcher.close();
      await queue;
      process.exit();
    });
} else {
  await schedule();
}
